"""Write docs/PLAYBOOK.md: reference cases for the road desk agent. Two sources, both real records:
(1) the dataset's executed or reviewed agent proposals with the operator's review note (how Bahn actually decided),
(2) our stored simulated calls (how a call should run and what it may and may not extract).
The playbook is examples to imitate, not rules: the rules stay in the brief's mustNot and the derived layer."""
import json, glob, os
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
L = lambda n: [json.loads(l) for l in open(f"{root}/data/dataset/{n}.jsonl")]
orders = {o["id"]: o for o in L("orders")}
out = ["# Road desk playbook: worked examples", "",
       "Generated by tools/playbook.py from the dataset's reviewed proposals and our simulated calls. Examples, not rules.", ""]
out += ["## How operators decided on agent proposals", ""]
for p in L("agent_proposals"):
    rv = p.get("review") or {}
    if not rv.get("decision_note"):
        continue
    err = (p.get("execution") or {}).get("error")
    out += [f"### {orders[p['order_id']]['reference']} - {p['summary']}",
            f"- Agent reasoning: {p['rationale']}",
            f"- Operator decision: **{rv['decision']}** - {rv['decision_note']}",
            f"- Outcome: {p['status']}" + (f"; error: {err}" if err else ""), ""]
out += ["## How a robo-call should run", ""]
seen = set()
for f in sorted(glob.glob(f"{root}/data/out/calls/*.json")):
    c = json.load(open(f))
    persona = c["id"].replace("call-sim-", "").rsplit("-", 1)[0]
    if persona in seen:
        continue
    seen.add(persona)
    out += [f"### {orders[c['orderId']]['reference']} - {c['brief']['purpose']} ({c['direction'].lower()}, {c['outcome'].lower()})"]
    if c.get("triage"):
        out += [f"- Triage from turn {c['triage']['turnSeq']}: {c['triage']['urgency']} / {c['triage']['situation']}"]
    out += ["- Transcript:"] + [f"    {t['speaker'].lower()}: {t['text']}" for t in c["turns"]]
    got = ", ".join(f"{s['value']['slot']}={json.dumps(s['value']['value'])}" for s in c["slots"]) or "nothing"
    out += [f"- Extracted (each a claim citing its turn): {got}"]
    missing = [a for a in c["brief"]["ask"] if not any(s["value"]["slot"] == a for s in c["slots"])]
    if missing:
        out += [f"- Not extracted, retry later: {', '.join(missing)}"]
    if c["toolCalls"]:
        out += ["- Tool calls: " + "; ".join(f"{t['name']}({t['argument'][:80]})" for t in c["toolCalls"])]
    out += [f"- Never said: {', '.join(c['brief']['mustNot'])}", ""]
open(f"{root}/docs/PLAYBOOK.md", "w").write("\n".join(out) + "\n")
print("wrote docs/PLAYBOOK.md", len(out), "lines,", len(seen), "call examples")
