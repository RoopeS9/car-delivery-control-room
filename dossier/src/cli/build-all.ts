// Build and validate a dossier for every order, write them to data/out, and regenerate docs/DOSSIER.md.
import { mkdirSync, writeFileSync } from "node:fs"
import { CLASSES, COLLECTION_CLASS, type ClassId } from "../classes"
import { DATASET_CLASSES, type Dossier } from "../dossier"
import { buildDossier, loadDataset } from "../build"
import { Strength } from "../strength"

const root = new URL("../../", import.meta.url)
const ds = loadDataset(new URL("data/dataset/", root))
mkdirSync(new URL("data/out/", root), { recursive: true })

const tok = (v: unknown) => Math.round(JSON.stringify(v).length / 4)
const perClass = new Map<string, number[]>(), totals: number[] = [], phases = new Map<string, number>()
const dangling = new Map<string, number>()
let built = 0
for (const o of ds.rows.orders) {
  const d: Dossier = buildDossier(ds, o.id)
  built++
  writeFileSync(new URL(`data/out/${o.reference}.json`, root), JSON.stringify(d, null, 1))
  totals.push(tok(d))
  phases.set(d.phase.phase, (phases.get(d.phase.phase) ?? 0) + 1)
  for (const k of DATASET_CLASSES) perClass.set(k, [...(perClass.get(k) ?? []), tok(d.classes[k])])
  for (const r of d.integrity.danglingRefs) dangling.set(`${r.fromCollection}.${r.field}`, (dangling.get(`${r.fromCollection}.${r.field}`) ?? 0) + 1)
}
const pct = (xs: number[], p: number) => [...xs].sort((a, b) => a - b)[Math.min(xs.length - 1, Math.floor(p * xs.length))] ?? 0
console.log(`built and validated ${built} dossiers`)
console.log(`size (JSON chars/4): median ${pct(totals, 0.5)}, p90 ${pct(totals, 0.9)}, max ${Math.max(...totals)} tokens`)
console.log("phases:", Object.fromEntries(phases))
console.log("per class median / max tokens:")
for (const k of DATASET_CLASSES) console.log(`  ${k.padEnd(14)} ${String(pct(perClass.get(k)!, 0.5)).padStart(6)} ${String(Math.max(...perClass.get(k)!)).padStart(6)}`)
console.log("dangling refs by field:", dangling.size ? Object.fromEntries(dangling) : "none")

// ---------------------------------------------------------------- docs/DOSSIER.md, generated from the registry
const collectionsOf = (k: ClassId) => Object.entries(COLLECTION_CLASS).filter(([, c]) => c === k).map(([n]) => `\`${n}\``).join(", ")
const lines: string[] = [
  "# Dossier schema", "",
  "Generated by `npm run build-all` from `src/classes.ts`, `src/strength.ts` and the built dossiers. Do not edit by hand.", "",
  "One dossier per order holds every record that concerns it, grouped into information classes. Each item carries its",
  "collection, id, primary time, evidence strength and membership (DIRECT names the order, JOINED is reached by a link,",
  "CANDIDATE might concern it). Records are validated by strict generated schemas: unknown keys, unknown enum values and",
  "malformed times are rejected.", "",
  `Measured on the snapshot: median ${pct(totals, 0.5)} tokens, p90 ${pct(totals, 0.9)}, max ${Math.max(...totals)} (JSON chars / 4), so the whole dossier always fits a reasoning model's context.`, "",
  "## Information classes", "",
  "| Class | Holds | Arrives (phase: when) | Aids | Voice card | Median tokens |", "|---|---|---|---|---|---|",
  ...(Object.keys(CLASSES) as ClassId[]).map((k) => {
    const s = CLASSES[k]
    const src = (DATASET_CLASSES as readonly string[]).includes(k) ? `<br>${collectionsOf(k)}` : "<br>live, see `src/live.ts`"
    const med = perClass.has(k) ? String(pct(perClass.get(k)!, 0.5)) : "n/a"
    return `| **${s.title}** (${k}) | ${s.holds}${src} | ${s.arrives.map((a) => `${a.phase}: ${a.when}`).join("<br>")} | ${s.aids.join(", ") || "none"} | ${s.voice} | ${med} |`
  }), "",
  "## Evidence strength", "",
  ...Strength.options.map((s) => `- \`${s}\``), "",
  "Rules per collection are in `src/strength.ts` and cite the packet's README and SCHEMA.md where the distinction comes from.", "",
]
mkdirSync(new URL("docs/", root), { recursive: true })
writeFileSync(new URL("docs/DOSSIER.md", root), lines.join("\n") + "\n")
console.log("wrote docs/DOSSIER.md")
